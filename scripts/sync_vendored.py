"""Sync vendored sources from upstream repos based on SOURCES.yaml.

Usage:
    python scripts/sync_vendored.py                # all vendored packages
    python scripts/sync_vendored.py pier           # one specific subpackage
    python scripts/sync_vendored.py --check        # regenerate and fail on any drift

For each manifest ``sgl_eval/_vendored/<pkg>/SOURCES.yaml``:
  1. Fetches the upstream tree at ``synced_from_sha`` (one tarball per repo).
  2. For every ``files`` entry, applies in order:
       ``replace``          ``{old, new, count}`` exact-text substitutions
       ``drop_statements``  ``{text, count}`` exact-text blocks removed
       ``drop_functions``   defs / classes / methods removed by name
       ``drop_imports``     ``from <prefix>`` / ``import <prefix>`` blocks removed
       ``import_rewrites``  textual rewrites so imports resolve under _vendored
     ``old`` / ``text`` blocks are written dedented in the manifest and matched
     against the upstream text at whatever common indentation they occur; the
     occurrence count must equal ``count`` (default 1), so a transform cannot
     silently stop applying after an upstream bump.
  3. Writes ``dst`` with a provenance banner (``.py`` / ``.yaml``); ``binary: true``
     copies bytes verbatim with no banner.
  4. With ``ensure_package_inits: true``, adds an ``__init__.py`` marker to every
     vendored directory that lacks one so setuptools ships it.

Idempotent: re-running with the same SHA yields the same files. ``--check``
regenerates into a temporary directory and diffs it against the tree.
"""

from __future__ import annotations

import argparse
import ast
import filecmp
import io
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path
from typing import Dict, Iterable, List, Optional

import yaml

ROOT = Path(__file__).resolve().parent.parent
VENDOR_ROOT = ROOT / "sgl_eval" / "_vendored"

BANNER_PY = (
    "# Vendored from {repo}@{sha}\n"
    "# Source: {src}\n"
    "# DO NOT EDIT directly. To upgrade, edit SOURCES.yaml and rerun\n"
    "# `python scripts/sync_vendored.py`.\n\n"
)
INIT_BANNER = "# Package marker generated by scripts/sync_vendored.py (ensure_package_inits).\n"
_MAX_INDENT = 64


class SyncError(RuntimeError):
    pass


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "packages",
        nargs="*",
        help="vendored subpackages to sync (default: all under sgl_eval/_vendored/)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="regenerate into a temp dir and exit 1 if any vendored file differs",
    )
    args = parser.parse_args(argv)

    pkgs = args.packages or [p.name for p in _vendored_packages()]
    if not pkgs:
        print("(no vendored packages found)")
        return 0

    rc = 0
    for name in pkgs:
        pkg_dir = VENDOR_ROOT / name
        manifest = pkg_dir / "SOURCES.yaml"
        if not manifest.exists():
            print(f"SKIP {name}: no SOURCES.yaml")
            rc = 1
            continue
        if args.check:
            rc |= check_one(pkg_dir, manifest)
        else:
            sync_one(pkg_dir, manifest, pkg_dir)
    return rc


def _vendored_packages() -> Iterable[Path]:
    if not VENDOR_ROOT.exists():
        return []
    return [p for p in VENDOR_ROOT.iterdir() if p.is_dir() and (p / "SOURCES.yaml").exists()]


def check_one(pkg_dir: Path, manifest: Path) -> int:
    with tempfile.TemporaryDirectory() as tmp:
        out_dir = Path(tmp) / pkg_dir.name
        produced = sync_one(pkg_dir, manifest, out_dir, quiet=True)
        drift = [
            rel
            for rel in produced
            if not (pkg_dir / rel).exists()
            or not filecmp.cmp(out_dir / rel, pkg_dir / rel, shallow=False)
        ]
    if drift:
        print(f"DRIFT {pkg_dir.relative_to(ROOT)}: {len(drift)} file(s) differ from a fresh sync")
        for rel in drift:
            print(f"    {rel}")
        return 1
    print(f"OK {pkg_dir.relative_to(ROOT)}: {len(produced)} files match a fresh sync")
    return 0


def sync_one(pkg_dir: Path, manifest: Path, out_dir: Path, *, quiet: bool = False) -> List[Path]:
    """Generate the package into ``out_dir``; return the produced paths relative to it."""
    spec = yaml.safe_load(manifest.read_text())
    repo = spec["upstream_repo"]
    sha = spec["synced_from_sha"]
    rewrites = spec.get("import_rewrites", {}) or {}
    files = spec.get("files", []) or []
    tree = load_tree(repo, sha)

    if not quiet:
        print(f"==> {pkg_dir.relative_to(ROOT)}  (upstream={repo}@{sha[:12]})")
    produced: List[Path] = []
    for entry in files:
        src = entry["src"]
        rel = Path(entry["dst"])
        dst = out_dir / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        if src not in tree:
            raise SyncError(f"{src} not found in {repo}@{sha[:12]}")
        payload = tree[src]

        if entry.get("binary", False):
            dst.write_bytes(payload)
            if not quiet:
                print(f"    wrote {rel}  ({len(payload)} bytes)")
            produced.append(rel)
            continue

        content = payload.decode()
        if dst.suffix == ".py":
            content = transform_source(content, entry, rewrites, label=src)
            dst.write_text(BANNER_PY.format(repo=repo, sha=sha, src=src) + content)
        elif dst.suffix in {".yaml", ".yml"}:
            dst.write_text(BANNER_PY.format(repo=repo, sha=sha, src=src) + content)
        else:
            dst.write_text(content)
        if not quiet:
            print(f"    wrote {rel}")
        produced.append(rel)

    if spec.get("ensure_package_inits", False):
        produced.extend(ensure_package_inits(out_dir, produced))
    return produced


def transform_source(content: str, entry: dict, rewrites: Dict[str, str], *, label: str) -> str:
    for block in entry.get("replace", []) or []:
        content = replace_block(content, block["old"], block["new"], block.get("count", 1), label)
    for block in entry.get("drop_statements", []) or []:
        content = replace_block(content, block["text"], "", block.get("count", 1), label)
    for fn in entry.get("drop_functions", []) or []:
        content = drop_function(content, fn)
    for prefix in entry.get("drop_imports", []) or []:
        content = drop_import(content, prefix)
    for old, new in rewrites.items():
        content = content.replace(old, new)
    return content


def replace_block(content: str, old: str, new: str, count: int, label: str) -> str:
    """Replace ``old`` (given dedented) at the one indentation where it occurs ``count`` times.

    Matches are anchored at line starts, so a block with N leading spaces in
    the source matches only at indent N, not at every smaller prefix.
    """
    matches = []
    for indent in range(_MAX_INDENT + 1):
        positions = _anchored_positions(content, _indent(old, indent))
        if positions:
            matches.append((indent, positions))
    if len(matches) != 1 or len(matches[0][1]) != count:
        detail = ", ".join(f"indent {i}: {len(p)}" for i, p in matches) or "no match"
        raise SyncError(
            f"{label}: expected {count} occurrence(s) of transform text ({detail}):\n{old}"
        )
    indent, positions = matches[0]
    needle, replacement = _indent(old, indent), _indent(new, indent)
    pieces, cursor = [], 0
    for pos in positions:
        pieces.append(content[cursor:pos])
        pieces.append(replacement)
        cursor = pos + len(needle)
    pieces.append(content[cursor:])
    return "".join(pieces)


def _anchored_positions(content: str, needle: str) -> List[int]:
    positions, start = [], 0
    while True:
        idx = content.find(needle, start)
        if idx < 0:
            return positions
        if idx == 0 or content[idx - 1] == "\n":
            positions.append(idx)
        start = idx + 1


def _indent(block: str, width: int) -> str:
    if width == 0:
        return block
    pad = " " * width
    return "".join(pad + line if line.strip() else line for line in block.splitlines(keepends=True))


def ensure_package_inits(out_dir: Path, produced: List[Path]) -> List[Path]:
    """Add ``__init__.py`` to every directory holding vendored files, up to the package root."""
    dirs = {Path(".")}
    for rel in produced:
        dirs.update(parent for parent in rel.parents if parent != Path("."))
    added: List[Path] = []
    for d in sorted(dirs):
        rel_init = d / "__init__.py"
        if rel_init in produced or (out_dir / rel_init).exists():
            continue
        (out_dir / rel_init).write_text(INIT_BANNER)
        added.append(rel_init)
    return added


_TREE_CACHE: Dict[tuple, Dict[str, bytes]] = {}


def load_tree(repo: str, sha: str) -> Dict[str, bytes]:
    """Fetch ``repo@sha`` once as a tarball and index it by repo-relative path."""
    key = (repo, sha)
    if key in _TREE_CACHE:
        return _TREE_CACHE[key]
    out = subprocess.check_output(["gh", "api", f"repos/{repo}/tarball/{sha}"])
    files: Dict[str, bytes] = {}
    with tarfile.open(fileobj=io.BytesIO(out), mode="r:gz") as tar:
        for member in tar.getmembers():
            if not member.isfile():
                continue
            # GitHub prefixes every member with `<owner>-<repo>-<sha7>/`.
            rel = member.name.split("/", 1)[1] if "/" in member.name else member.name
            handle: Optional[io.BufferedReader] = tar.extractfile(member)  # type: ignore[assignment]
            if handle is not None:
                files[rel] = handle.read()
    _TREE_CACHE[key] = files
    return files


def drop_function(content: str, name: str) -> str:
    """Remove a top-level def or class method named `name` from `content`."""
    tree = ast.parse(content)
    spans: list[tuple[int, int]] = []

    for node in ast.walk(tree):
        if (
            isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
            and node.name == name
        ):
            spans.append((node.lineno, node.end_lineno or node.lineno))

    if not spans:
        return content

    return _drop_line_ranges(content, spans)


def drop_import(content: str, module_prefix: str) -> str:
    """Remove ``from <module>...`` and ``import <module>...`` blocks where
    the module path starts with ``module_prefix``."""
    tree = ast.parse(content)
    spans: list[tuple[int, int]] = []

    for node in ast.iter_child_nodes(tree):
        if isinstance(node, ast.ImportFrom):
            if node.module and (
                node.module == module_prefix or node.module.startswith(module_prefix + ".")
            ):
                spans.append((node.lineno, node.end_lineno or node.lineno))
        elif isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name == module_prefix or alias.name.startswith(module_prefix + "."):
                    spans.append((node.lineno, node.end_lineno or node.lineno))
                    break

    if not spans:
        return content
    return _drop_line_ranges(content, spans)


def _drop_line_ranges(content: str, spans: list[tuple[int, int]]) -> str:
    lines = content.split("\n")
    drop = set()
    for start, end in spans:
        for i in range(start - 1, end):
            drop.add(i)
    return "\n".join(line for idx, line in enumerate(lines) if idx not in drop)


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except SyncError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        raise SystemExit(1)
